// Widen every leaf literal string to `string` so that other language files
// (tr, es, de, fr) are not forced to match exact string literals.
type DeepStringify<T> =
  T extends readonly (infer U)[] ? readonly DeepStringify<U>[] :
  T extends string ? string :
  T extends object ? { [K in keyof T]: DeepStringify<T[K]> } :
  T

export type TranslationKeys = DeepStringify<typeof en>
